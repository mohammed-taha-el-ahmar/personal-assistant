export function formatDate(d: Date, lang: Lang): string {
  // Western digits in both languages (common in the Maghreb and in tech writing).
  return d.toLocaleDateString(lang === 'ar' ? 'ar-u-nu-latn' : 'en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' });
}

// locale: used for Intl formatting. Arabic uses Latin digits (0-9), as is usual in the Maghreb;
// use "ar" instead of "ar-u-nu-latn" for Arabic-Indic digits.
const LANG_META = {
  en: { name: "English", dir: "ltr", locale: "en" },
  fr: { name: "Français", dir: "ltr", locale: "fr" },
  ar: { name: "العربية", dir: "rtl", locale: "ar-u-nu-latn" },
};

const LANGS = Object.keys(LANG_META);
let lang = (() => {
  try {
    const saved = localStorage.getItem("quizlive:lang");
    if (LANGS.includes(saved)) return saved;
  } catch { /* storage blocked */ }
  const nav = (navigator.language || "en").toLowerCase();
  return LANGS.find((l) => nav.startsWith(l)) || "en";
})();
const listeners = new Set();
const pluralRules = {};

export const getLang = () => lang;
export const getDir = () => LANG_META[lang].dir;
export const intlLocale = () => LANG_META[lang].locale;

// Plurals follow the language's own rules (Arabic has six forms):
// "key_one", "key_two", "key_few", "key_many", "key_zero" are used when defined, otherwise "key".
export function t(key, vars = {}) {
  const dict = DICT[lang];
  let k = key;
  if (typeof vars.n === "number") {
    pluralRules[lang] ||= new Intl.PluralRules(intlLocale());
    const form = `${key}_${pluralRules[lang].select(vars.n)}`;
    if (form in dict) k = form;
  }
  const s = dict[k] ?? DICT.en[k] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? ""));
}

export function ordinal(n) {
  if (lang === "fr") return n === 1 ? "1er" : `${n}e`;
  if (lang === "ar") return String(n);
  const s = ["th", "st", "nd", "rd"], v = n % 100;
  return n + (s[(v - 20) % 10] || s[v] || s[0]);
}

export const shapeName = (i) => SHAPE_NAMES[lang][i];

export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  document.documentElement.dir = getDir();
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
}

export function setLang(next) {
  if (!LANGS.includes(next) || next === lang) return;
  lang = next;
  try { localStorage.setItem("quizlive:lang", lang); } catch { /* ignore */ }
  applyI18n();
  listeners.forEach((fn) => fn(lang));
}

export const onLangChange = (fn) => listeners.add(fn);

export function initI18n() {
  // Set direction immediately so right-to-left pages don't flash left-to-right.
  document.documentElement.dir = getDir();
  document.documentElement.lang = lang;
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", () => applyI18n());
  else applyI18n();
}

// Language picker: each option is written in its own language.
export function mountLangToggle(container) {
  const select = document.createElement("select");
  select.className = "lang-select";
  select.innerHTML = LANGS.map((l) =>
    `<option value="${l}" lang="${l}" dir="${LANG_META[l].dir}">${LANG_META[l].name}</option>`).join("");
  const sync = () => {
    select.value = lang;
    select.setAttribute("aria-label", t("lang.switch"));
    select.title = t("lang.switch");
  };
  select.addEventListener("change", () => setLang(select.value));
  onLangChange(sync);
  sync();
  container.append(select);
  return select;
}

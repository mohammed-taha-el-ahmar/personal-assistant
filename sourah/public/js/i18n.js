let lang = 'fr';
export function setLang(l) { lang = D[l] ? l : 'fr'; document.documentElement.lang = lang; document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'; }
export function getLang() { return lang; }
export function detectLang() {
  const nav = (navigator.language || 'fr').slice(0, 2);
  return D[nav] ? nav : 'en';
}
export function t(key, vars) {
  let s = (D[lang] && D[lang][key]) ?? D.fr[key] ?? key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}
// Plural: Arabic uses the "other" form from 3 to 10 and singular otherwise in our short labels.
t.n = function (key, n, vars) {
  const num = fmtNum(n);
  let form;
  if (lang === 'ar') form = n >= 3 && n <= 10 ? 'other' : 'one';
  else if (lang === 'fr') form = n > 1 ? 'other' : 'one';
  else form = n === 1 ? 'one' : 'other';
  return t(key + '_' + form, Object.assign({ n: num }, vars || {}));
};
export const listSep = () => (lang === 'ar' ? '، ' : ', ');
export function fmtNum(n) { return Number(n).toLocaleString(locale()); }
export function locale() { return lang === 'ar' ? 'ar-EG' : lang === 'en' ? 'en-GB' : 'fr-FR'; }
export function dictKeys() { return { fr: Object.keys(D.fr), en: Object.keys(D.en), ar: Object.keys(D.ar) }; }

#!/usr/bin/env node
// Builds everything derived from the content in docs/, so the website and the assistant never drift:
//
//   1. docs/projects-summary.md      human-readable portfolio summary (from projects.json)
//   2. worker/src/generated/kb.js    the assistant's knowledge base: small, titled chunks bundled
//                                    into the Worker (no runtime fetch, fits small-context models)
//
//   node scripts/build-content.mjs          → writes both files
//   node scripts/build-content.mjs --check  → exits 1 if either is out of date (used in CI)
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { chunkMarkdown, projectChunks, estimateTokens } from './lib/chunk.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const p = (rel) => path.join(root, rel);

const STATUS_LABEL = { live: 'Live', complete: 'Complete', in_progress: 'In Progress', planned: 'Planned' };
const KNOWN_STATUSES = new Set([...Object.keys(STATUS_LABEL), 'private']);

// Markdown documents the assistant can draw on. `label` is shown on source chips.
const MARKDOWN_DOCS = [
  { key: 'resume', file: 'docs/resume.md', label: 'Resume', pinned: ['Profile'] },
  { key: 'faq', file: 'docs/faq.md', label: 'FAQ' },
  { key: 'projects', file: 'docs/projects.md', label: 'Work projects' },
];

function renderSummary(projects) {
  const lines = ['# Projects & Technical Demos — Summary', ''];
  for (const pr of projects) {
    lines.push(`### ${pr.title} [${STATUS_LABEL[pr.status] ?? pr.status}]`);
    if (pr.value) lines.push(pr.value);
    if (pr.architecture) lines.push(`Architecture: ${pr.architecture}`);
    if (pr.tags?.length) lines.push(`Stack: ${pr.tags.join(', ')}`);
    if (pr.github) lines.push(`GitHub: ${pr.github}`);
    if (pr.article) lines.push(`Article: ${pr.article}`);
    lines.push('');
  }
  return lines.join('\n');
}

function validate(projects) {
  const errors = [];
  const ids = new Set();
  projects.forEach((pr, i) => {
    const where = `projects[${i}] (${pr.id ?? 'no id'})`;
    for (const field of ['id', 'title', 'status', 'value']) if (!pr[field]) errors.push(`${where}: missing "${field}"`);
    if (pr.id && ids.has(pr.id)) errors.push(`${where}: duplicate id`);
    ids.add(pr.id);
    if (pr.status && !KNOWN_STATUSES.has(pr.status)) errors.push(`${where}: unknown status "${pr.status}"`);
    for (const key of ['github', 'article']) {
      if (pr[key] && !/^https:\/\//.test(pr[key])) errors.push(`${where}: "${key}" must be an https URL`);
    }
  });
  return errors;
}

async function buildKb(projects) {
  const chunks = [];
  for (const doc of MARKDOWN_DOCS) {
    const md = await readFile(p(doc.file), 'utf8');
    chunks.push(...chunkMarkdown(doc.key, md, { label: doc.label, pinned: doc.pinned ?? [] }));
  }
  chunks.push(...projects.flatMap(projectChunks));
  const tokens = chunks.reduce((n, c) => n + estimateTokens(c.text), 0);
  const body = JSON.stringify({ chunks }, null, 1);
  return {
    source:
      '// GENERATED by scripts/build-content.mjs from docs/ — do not edit by hand.\n' +
      `// ${chunks.length} chunks, ~${tokens} tokens in total.\n` +
      `export default ${body};\n`,
    count: chunks.length,
    tokens,
  };
}

const { projects: allProjects } = JSON.parse(await readFile(p('docs/projects.json'), 'utf8'));
const errors = validate(allProjects);
if (errors.length) {
  console.error(`docs/projects.json has ${errors.length} problem(s):\n- ${errors.join('\n- ')}`);
  process.exit(1);
}
const projects = allProjects.filter((pr) => pr.status !== 'private');

const kb = await buildKb(projects);
const outputs = [
  ['docs/projects-summary.md', renderSummary(projects)],
  ['worker/src/generated/kb.js', kb.source],
];

if (process.argv.includes('--check')) {
  let stale = false;
  for (const [rel, content] of outputs) {
    const current = await readFile(p(rel), 'utf8').catch(() => '');
    if (current !== content) {
      console.error(`${rel} is out of date. Run: npm run build:content`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log('Content is up to date.');
} else {
  await mkdir(p('worker/src/generated'), { recursive: true });
  for (const [rel, content] of outputs) await writeFile(p(rel), content);
  console.log(
    `Wrote docs/projects-summary.md and worker/src/generated/kb.js (${kb.count} chunks, ~${kb.tokens} tokens).`,
  );
}
